<script>
document.addEventListener("DOMContentLoaded", () => {

    // Flip card on click
    document.querySelectorAll(".card").forEach(card => {
        card.addEventListener("click", (e) => {
            // Prevent double toggle if clicking rapidly
            card.classList.toggle("flip");
        });
    });

    // FAQ toggle with open class for animation
    document.querySelectorAll('.faq-item h4').forEach(q => {
        q.addEventListener('click', function () {
            const p = this.nextElementSibling;
            const isOpen = p.style.display === "block";

            // Close all other open FAQs
            document.querySelectorAll('.faq-item p').forEach(item => {
                item.style.display = "none";
            });
            document.querySelectorAll('.faq-item h4').forEach(heading => {
                heading.classList.remove('open');
            });

            // Toggle current
            if (!isOpen) {
                p.style.display = "block";
                this.classList.add('open');
            } else {
                p.style.display = "none";
                this.classList.remove('open');
            }
        });
    });

    // Smooth scroll for CTA
    document.querySelector('.hero-cta')?.addEventListener('click', function(e) {
        e.preventDefault();
        const target = document.querySelector(this.getAttribute('href'));
        if (target) {
            target.scrollIntoView({ behavior: 'smooth', block: 'start' });
        }
    });

});
</script>

